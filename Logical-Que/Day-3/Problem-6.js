// Swap Two Variables Without Temporary Variable


// Array Destructuring

let a = 23;
let b = 12;

[a,b] = [b,a];

console.log(a);
console.log(b);


// Addition and Subtraction

let c = 12;
let d = 45;

c = c+d;
d = c-d;
c = c-d;

console.log(c);
console.log(d);



// Multi and Division

let e = 10;
let f = 20;

e = e*f;
f = e/f;
e = e/f;


console.log(e)
console.log(f)



